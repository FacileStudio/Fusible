import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

type PeripheralPin = { pin: string; signal: string; af?: number };
type Peripheral = { name: string; pins?: PeripheralPin[] };
type Package = { name: string; pins: { signals: string[] }[] };
type Chip = { name: string; packages: Package[]; cores: { peripherals: Peripheral[]; pins: { name: string }[] }[] };

const FAMILIES = ["g0", "g4", "f4", "l4", "h7"];
const GPIO = /^P[A-K]\d{1,2}$/;
const OUT = "src/silicon/data";
const UPSTREAM = "https://github.com/embassy-rs/stm32-data-generated";

/** Maps one peripheral pin of stm32-data to a Fusible signal token, or null when Fusible cannot express it. */
function token(peripheral: string, p: PeripheralPin): string | null {
  const m = peripheral.match(/^(USART|UART|SPI|I2C|ADC|USB|USB_OTG_FS|USB_OTG_HS)(\d*)$/);
  if (!m || m[2].length > 1) return null;
  const [, kind, inst] = m;
  if (kind === "ADC") {
    const ch = p.signal.match(/^INP?(\d+)$/);
    return ch ? `ADC${inst}_IN${ch[1]}` : null;
  }
  if (kind.startsWith("USB")) return ["DM", "DP"].includes(p.signal) ? `USB_${p.signal}` : null;
  const tails: Record<string, Record<string, string>> = {
    USART: { TX: "TX", RX: "RX", CTS: "CTS", RTS: "RTS" },
    UART: { TX: "TX", RX: "RX", CTS: "CTS", RTS: "RTS" },
    SPI: { SCK: "SCK", MISO: "MISO", MOSI: "MOSI", NSS: "CS0" },
    I2C: { SCL: "SCL", SDA: "SDA" },
  };
  const tail = tails[kind][p.signal];
  if (!tail || p.af === undefined) return null;
  const prefix = kind === "USART" ? "UART" : kind;
  return `${prefix}${inst}_${tail}:${p.af}`;
}

/** Pin name to its sorted signal tokens for the first core of a chip, SWD added on PA13 and PA14. */
function table(chip: Chip): Map<string, string[]> {
  const core = chip.cores[0];
  const pins = new Map<string, Set<string>>();
  for (const pin of core.pins) if (GPIO.test(pin.name)) pins.set(pin.name, new Set());
  for (const peripheral of core.peripherals) {
    for (const p of peripheral.pins ?? []) {
      const t = token(peripheral.name, p);
      if (t && pins.has(p.pin)) pins.get(p.pin)!.add(t);
    }
  }
  pins.get("PA13")?.add("SWD_DIO:0");
  pins.get("PA14")?.add("SWD_CLK:0");
  const sorted = [...pins.keys()].sort(byPin);
  return new Map(sorted.map((name) => [name, [...pins.get(name)!].sort()]));
}

/** Orders `PA2` before `PA10` and port A before port B. */
function byPin(a: string, b: string): number {
  return a[1] === b[1] ? Number(a.slice(2)) - Number(b.slice(2)) : a.charCodeAt(1) - b.charCodeAt(1);
}

/** Lines of one package: its name and the GPIOs it bonds out that the table knows. */
function packageLine(pkg: Package, known: Map<string, string[]>): string {
  const bonded = new Set(pkg.pins.flatMap((p) => p.signals).filter((s) => known.has(s)));
  return `pkg ${pkg.name} ${[...bonded].sort(byPin).join(" ")}`;
}

/** Text of one family file: header, then one `table` block per distinct pin table and its packages. */
function family(chips: Chip[], commit: string): string {
  const blocks = new Map<string, { rows: Map<string, string[]>; pkgs: string[] }>();
  for (const chip of chips) {
    const rows = table(chip);
    const key = JSON.stringify([...rows]);
    if (!blocks.has(key)) blocks.set(key, { rows, pkgs: [] });
    for (const pkg of chip.packages) blocks.get(key)!.pkgs.push(packageLine(pkg, rows));
  }
  const lines = [
    `# Generated by scripts/silicon-gen.ts from ${UPSTREAM} at ${commit}.`,
    "# Upstream data is MIT OR Apache-2.0, see LICENSE-stm32-data. Do not edit by hand.",
  ];
  for (const { rows, pkgs } of blocks.values()) {
    lines.push("table");
    for (const [pin, tokens] of rows) lines.push([pin, ...tokens].join(" "));
    lines.push(...pkgs);
  }
  return lines.join("\n") + "\n";
}

/** Upstream checkout commit, read from git. */
function commitOf(dir: string): string {
  const out = Bun.spawnSync(["git", "-C", dir, "rev-parse", "HEAD"]);
  return out.stdout.toString().trim() || "unknown";
}

/** Reads every chip file of the requested families and writes one data file per family. */
function main(dir: string | undefined): void {
  if (!dir) throw new Error("usage: bun scripts/silicon-gen.ts <stm32-data-generated checkout>");
  const chipsDir = join(dir, "data", "chips");
  const commit = commitOf(dir);
  mkdirSync(OUT, { recursive: true });
  const files = readdirSync(chipsDir).filter((f) => f.endsWith(".json")).sort();
  for (const fam of FAMILIES) {
    const prefix = `STM32${fam.toUpperCase()}`;
    const chips = files
      .filter((f) => f.startsWith(prefix))
      .map((f) => JSON.parse(readFileSync(join(chipsDir, f), "utf8")) as Chip);
    writeFileSync(join(OUT, `stm32${fam}.txt`), family(chips, commit));
    console.log(`wrote ${OUT}/stm32${fam}.txt (${chips.length} chips)`);
  }
}

main(process.argv[2]);
