import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

type Rule = {
  id: string;
  category: string;
  summary: string;
  severity: string;
  standard: string | null;
  source_url: string | null;
  waivable: boolean;
};

const root = resolve(import.meta.dir, "..");
const outDir = join(root, "docs/rules");
const binary = resolve(root, process.env.FUSIBLE_BIN ?? "target/debug/fusible");
const check = process.argv.includes("--check");

function loadRules(): Rule[] {
  const run = Bun.spawnSync([binary, "rules", "--json"], { cwd: tmpdir() });
  if (run.exitCode !== 0) {
    throw new Error(`${binary} rules --json exited ${run.exitCode}: ${run.stderr.toString()}`);
  }
  return JSON.parse(run.stdout.toString()) as Rule[];
}

function rulePage(rule: Rule): string {
  const lines = [`# \`${rule.id}\``, "", rule.summary, "", "| Field | Value |", "| --- | --- |"];
  lines.push(`| Category | ${rule.category} |`, `| Default severity | ${rule.severity} |`);
  if (rule.standard) lines.push(`| Standard | ${rule.standard} |`);
  if (rule.source_url) lines.push(`| Source | ${rule.source_url} |`);
  lines.push("", "## Change its level", "");
  if (!rule.waivable) {
    lines.push("This rule guards the netlist. It stays an error and no waiver applies.", "");
  } else {
    lines.push("```yaml", "rules:", `  ${rule.id}: warning`, "", "waivers:", `  - rule: ${rule.id}`);
    lines.push("    match: U1.VDD", "    reason: why this case is safe", "```", "");
  }
  lines.push(`Run \`fusible explain ${rule.id}\` for the level this project gives it.`, "");
  return lines.join("\n");
}

function indexPage(rules: Rule[]): string {
  const lines = ["# Rules", "", "Generated by `scripts/rules-doc.ts` from `fusible rules --json`. Do not edit.", ""];
  lines.push("| Rule | Category | Severity | Summary |", "| --- | --- | --- | --- |");
  for (const rule of rules) {
    const summary = rule.summary.replaceAll("|", "\\|");
    lines.push(`| [\`${rule.id}\`](${rule.id}.md) | ${rule.category} | ${rule.severity} | ${summary} |`);
  }
  lines.push("");
  return lines.join("\n");
}

function expected(rules: Rule[]): Map<string, string> {
  const pages = new Map<string, string>([["README.md", indexPage(rules)]]);
  for (const rule of rules) pages.set(`${rule.id}.md`, rulePage(rule));
  return pages;
}

function differences(pages: Map<string, string>): string[] {
  const present = existsSync(outDir) ? readdirSync(outDir).filter((f) => f.endsWith(".md")) : [];
  const stale = present.filter((file) => !pages.has(file));
  const changed = [...pages].filter(([file, text]) => {
    const path = join(outDir, file);
    return !existsSync(path) || readFileSync(path, "utf8") !== text;
  });
  return [...stale, ...changed.map(([file]) => file)];
}

function write(pages: Map<string, string>): void {
  mkdirSync(outDir, { recursive: true });
  for (const file of readdirSync(outDir)) {
    if (file.endsWith(".md") && !pages.has(file)) rmSync(join(outDir, file));
  }
  for (const [file, text] of pages) writeFileSync(join(outDir, file), text);
  console.log(`wrote ${pages.size} pages to docs/rules`);
}

const pages = expected(loadRules());
const diff = differences(pages);
if (!check) {
  write(pages);
} else if (diff.length > 0) {
  console.error(`docs/rules is out of date: ${diff.join(", ")}. Run bun scripts/rules-doc.ts.`);
  process.exit(1);
}
