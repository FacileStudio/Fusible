//! Markdown of the bring-up sheet.

use std::fmt::Write;

use super::debug::Connector;
use super::rails::Rail;
use super::straps::Strap;

/// Everything `bringup.md` lists for one board.
pub struct Sheet {
    pub board: String,
    pub mcu: Option<String>,
    pub rails: Vec<Rail>,
    pub straps: Vec<Strap>,
    pub connectors: Vec<Connector>,
}

/// Escapes `|` so a value stays in its table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

/// The Markdown text of `sheet`.
pub fn markdown(sheet: &Sheet) -> String {
    let mut out = format!("# Bring-up: {}\n\n", cell(&sheet.board));
    let mcu = sheet.mcu.as_deref().unwrap_or("not identified");
    let _ = writeln!(out, "Generated by Fusible. MCU: {}.\n", cell(mcu));
    rails(&mut out, &sheet.rails);
    straps(&mut out, &sheet.straps);
    connectors(&mut out, &sheet.connectors);
    out
}

fn rails(out: &mut String, rails: &[Rail]) {
    out.push_str("## Power rails\n\nPower them up and probe them in this order.\n\n");
    if rails.is_empty() {
        out.push_str("No rail found. Declare rails under `nets:` with a `voltage`.\n\n");
        return;
    }
    out.push_str("| # | Rail | Expected | Fed by | Probe |\n|---|---|---|---|---|\n");
    for (i, rail) in rails.iter().enumerate() {
        let volts = rail
            .voltage
            .map_or_else(|| "unknown".to_string(), |v| format!("{v} V"));
        let fed = match rail.fed_by.is_empty() {
            true => "source".to_string(),
            false => rail.fed_by.join(", "),
        };
        let _ = writeln!(
            out,
            "| {} | {} | {volts} | {} | {} |",
            i + 1,
            cell(&rail.name),
            cell(&fed),
            cell(&rail.probe)
        );
    }
    out.push('\n');
}

fn straps(out: &mut String, straps: &[Strap]) {
    out.push_str("## Strap pins\n\n");
    if straps.is_empty() {
        out.push_str("The silicon table lists no strap pin for this MCU.\n\n");
        return;
    }
    out.push_str(
        "| Pin | Must be at reset | Purpose | Net | On this board |\n|---|---|---|---|---|\n",
    );
    for s in straps {
        let net = if s.net.is_empty() { "none" } else { &s.net };
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            s.pin,
            s.level,
            s.purpose,
            cell(net),
            cell(&s.state)
        );
    }
    out.push('\n');
}

fn connectors(out: &mut String, connectors: &[Connector]) {
    out.push_str("## Debug and programming connectors\n\n");
    if connectors.is_empty() {
        out.push_str("No connector reaches an MCU debug, boot, reset, UART or USB pin.\n");
        return;
    }
    for c in connectors {
        let _ = writeln!(
            out,
            "### {}\n\n| Pin | Net | MCU pin |\n|---|---|---|",
            cell(&c.name)
        );
        for p in &c.pins {
            let _ = writeln!(
                out,
                "| {} | {} | {} |",
                cell(&p.pin),
                cell(&p.net),
                cell(p.mcu.as_deref().unwrap_or("-"))
            );
        }
        out.push('\n');
    }
}
