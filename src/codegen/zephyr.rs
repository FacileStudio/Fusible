//! Zephyr devicetree overlay. EXPERIMENTAL: no Zephyr build checks it.
//!
//! STM32 buses use the `hal_stm32` pinctrl labels (`i2c1_scl_pb8`). Other
//! families get one `pinctrl` group per bus (`I2C0_SDA_P4` on RP2040,
//! `I2C0_SDA_GPIO4` on ESP32). Free pins and ADC inputs go to `zephyr,user`.

use std::fmt::Write;

use super::model::{BoardBindings, BusPin};
use super::render::comment_text;
use super::view::{buses, Bus, Family, Kind};

/// The overlay text.
pub fn overlay(b: &BoardBindings) -> String {
    let family = Family::of(&b.mcu.chip);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "/* Generated by Fusible from board `{}` ({}).",
        text(&b.board),
        text(&b.mcu.chip)
    );
    out.push_str(" * EXPERIMENTAL: no Zephyr build checked this overlay. DO NOT EDIT. */\n\n");
    out.push_str("#include <zephyr/dt-bindings/gpio/gpio.h>\n");
    let buses = buses(b);
    if family != Family::Stm32 && !buses.is_empty() {
        out.push_str("\n&pinctrl {\n");
        buses
            .iter()
            .for_each(|bus| pinctrl_group(&mut out, bus, family));
        out.push_str("};\n");
    }
    for bus in &buses {
        bus_node(&mut out, bus, family);
    }
    user_node(&mut out, b, family);
    out
}

fn text(s: &str) -> String {
    comment_text(s).replace("*/", "* /")
}

fn node(bus: &Bus) -> String {
    bus.name.to_ascii_lowercase()
}

fn pin_suffix(pin: &BusPin, family: Family) -> String {
    match family {
        Family::Rp => format!("P{}", pin.number),
        Family::Stm32 => pin.label.clone(),
        _ => format!("GPIO{}", pin.number),
    }
}

fn pinctrl_group(out: &mut String, bus: &Bus, family: Family) {
    let mux: Vec<String> = bus
        .lines
        .iter()
        .map(|(role, p)| {
            let role = role.to_ascii_uppercase();
            match (family, bus.kind, bus.instance) {
                (Family::Esp, Kind::Spi, Some(n)) => {
                    let role = if role == "SCK" {
                        "SCLK".to_string()
                    } else {
                        role
                    };
                    format!("<SPIM{n}_{role}_{}>", pin_suffix(p, family))
                }
                _ => format!("<{}_{role}_{}>", bus.name, pin_suffix(p, family)),
            }
        })
        .collect();
    let input = if bus.kind == Kind::I2c {
        "\n\t\t\tinput-enable;"
    } else {
        ""
    };
    let _ = writeln!(
        out,
        "\t{0}_default: {0}_default {{\n\t\tgroup1 {{\n\t\t\tpinmux = {1};{input}\n\t\t}};\n\t}};",
        node(bus),
        mux.join(", ")
    );
}

fn bus_node(out: &mut String, bus: &Bus, family: Family) {
    let pinctrl = match family {
        Family::Stm32 => {
            let labels: Vec<String> = bus
                .lines
                .iter()
                .map(|(role, p)| format!("&{}_{role}_{}", node(bus), p.label.to_ascii_lowercase()))
                .collect();
            labels.join(" ")
        }
        _ => format!("&{}_default", node(bus)),
    };
    let _ = writeln!(out, "\n&{} {{\n\tpinctrl-0 = <{pinctrl}>;", node(bus));
    out.push_str("\tpinctrl-names = \"default\";\n\tstatus = \"okay\";\n");
    if !bus.chip_selects.is_empty() {
        let cs: Vec<String> = bus
            .chip_selects
            .iter()
            .map(|(p, _)| format!("<{} GPIO_ACTIVE_LOW>", gpio_ref(p, family)))
            .collect();
        let _ = writeln!(out, "\tcs-gpios = {};", cs.join(", "));
    }
    for device in &bus.devices {
        let _ = writeln!(
            out,
            "\t/* device: {} (add its node with compatible and reg) */",
            text(device)
        );
    }
    out.push_str("};\n");
}

/// `&gpiob 0` for STM32 `PB0`, `&gpio0 4` elsewhere (`&gpio1` above 31).
fn gpio_ref(pin: &BusPin, family: Family) -> String {
    match crate::silicon::model::parse_port_pin(&pin.label).filter(|_| family == Family::Stm32) {
        Some((port, n)) => format!("&gpio{} {n}", port.to_ascii_lowercase()),
        None => format!("&gpio{} {}", pin.number / 32, pin.number % 32),
    }
}

fn user_node(out: &mut String, b: &BoardBindings, family: Family) {
    out.push_str("\n/ {\n\tzephyr,user {\n");
    let channels: Vec<String> = b
        .adc
        .iter()
        .filter_map(|a| {
            a.channel.map(|(adc, ch)| {
                format!(
                    "<&adc{} {ch}>",
                    if family == Family::Stm32 { adc } else { 0 }
                )
            })
        })
        .collect();
    if !channels.is_empty() {
        let _ = writeln!(out, "\t\tio-channels = {};", channels.join(", "));
    }
    for pin in &b.gpio {
        let name = pin.signal.to_ascii_lowercase().replace('_', "-");
        let _ = writeln!(
            out,
            "\t\t{name}-gpios = <{} GPIO_ACTIVE_HIGH>;",
            gpio_ref(pin, family)
        );
    }
    out.push_str("\t};\n};\n");
}
