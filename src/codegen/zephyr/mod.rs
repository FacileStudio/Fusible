//! Zephyr devicetree overlay. EXPERIMENTAL: no Zephyr build checks it.
//!
//! Each bus gets its controller node with pinctrl, `status = "okay"` and a
//! child node per device: `reg` is the I2C address or the chip-select index,
//! `compatible` and the address come from `firmware.<name>.zephyr` in the
//! manifest, else from the part table ([`table`]). A part neither names gets a
//! disabled node marked `FUSIBLE TODO`, and the reason goes to
//! [`Overlay::todo`]. ADC inputs get channel nodes, `zephyr,user` entries and,
//! behind a divider, a `voltage-divider` node; LEDs and buttons whose polarity
//! the netlist shows get `gpio-leds` and `gpio-keys` nodes.
//!
//! STM32 buses use the `hal_stm32` pinctrl labels (`i2c1_scl_pb8`). RP2040,
//! RP2350 and ESP32 get one `<bus>_fusible` pinctrl state per bus, named apart
//! from the board's own `<bus>_default` states.

