/// Devicetree facts the manifest gives, by part designator.
pub type Overrides = BTreeMap<String, ZephyrDevice>;

/// An overlay, and what the user must fill in before it describes every part.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Overlay {
    pub text: String,
    pub todo: Vec<String>,
}

/// The board, its SoC conventions, the manifest facts, and the text so far.
struct Out<'a> {
    b: &'a BoardBindings,
    soc: Soc,
    overrides: &'a Overrides,
    text: String,
    todo: Vec<String>,
}

impl Out<'_> {
    fn line(&mut self, depth: usize, line: &str) {
        let _ = writeln!(self.text, "{}{line}", "\t".repeat(depth));
    }

    /// Records a missing fact and marks the spot in the overlay.
    fn todo(&mut self, depth: usize, what: &str, why: &str) {
        self.line(
            depth,
            &format!("/* FUSIBLE TODO {}: {} */", text(what), text(why)),
        );
        self.todo.push(format!("{what}: {why}"));
    }
}

/// The overlay of `b`, with `overrides` naming parts the part table does not know.
pub fn overlay(b: &BoardBindings, overrides: &Overrides) -> Overlay {
    let mut out = Out {
        b,
        soc: Soc::of(&b.mcu.chip),
        overrides,
        text: String::new(),
        todo: Vec::new(),
    };
    header(&mut out);
    let buses = buses(b);
    pinctrl::block(&mut out, &buses);
    for bus in &buses {
        bus::node(&mut out, bus);
    }
    analog::adc_nodes(&mut out);
    high_bank(&mut out);
    root::root(&mut out);
    bus::unused_overrides(&mut out, &buses);
    Overlay {
        text: out.text,
        todo: out.todo,
    }
}

fn header(out: &mut Out) {
    let (board, chip) = (text(&out.b.board), text(&out.b.mcu.chip));
    out.line(
        0,
        &format!("/* Generated by Fusible from board `{board}` ({chip})."),
    );
    out.line(
        0,
        " * EXPERIMENTAL: no Zephyr build checked this overlay. DO NOT EDIT. */\n",
    );
    out.line(0, "#include <zephyr/dt-bindings/gpio/gpio.h>");
    if out.b.adc.iter().any(|a| a.channel.is_some()) {
        out.line(0, "#include <zephyr/dt-bindings/adc/adc.h>");
    }
    if let Some(header) = out.soc.pinctrl_header() {
        out.line(
            0,
            &format!("#include <zephyr/dt-bindings/pinctrl/{header}>"),
        );
    }
}

/// Enables `gpio0_hi`, disabled in `rp2350.dtsi`, when an RP2350B pin above 31 is used.
fn high_bank(out: &mut Out) {
    if out.soc.is("rp2350b") && out.b.mcu.pins.iter().any(|p| p.pin_number >= 32) {
        out.line(0, "\n&gpio0_hi {\n\tstatus = \"okay\";\n};");
    }
}

fn text(s: &str) -> String {
    comment_text(s).replace("*/", "* /")
}

/// A devicetree label from a designator or signal: `u2`, `vbat_sense`.
fn label(name: &str) -> String {
    let clean: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    if clean.starts_with(|c: char| c.is_ascii_digit()) || clean.is_empty() {
        format!("_{clean}")
    } else {
        clean
    }
}

/// A devicetree node name from a designator or signal: `u2`, `vbat-sense`.
fn node_name(name: &str) -> String {
    let node = label(name).replace('_', "-");
    if node.starts_with('-') {
        format!("node{node}")
    } else {
        node
    }
}
