//! IPC-D-356A bare-board test netlist (`netlist.ipc`).
//!
//! Fixed-column records, metric (`UNITS CUST 1`: lengths in 0.001 mm,
//! angles in degrees). `317` is a plated through terminal, `327` an SMT
//! pad, `367` a non-plated hole. A net name longer than 14 characters is
//! written as `NNAME<n>` and spelled out in a `P  NNAME<n>` header line.

mod holes;
mod terminals;

use std::collections::BTreeMap;

use crate::netlist::Netlist;
use crate::parser::Circuit;

const NAME_WIDTH: usize = 14;
const MAX_SIZE: i64 = 9999;
const MAX_COORD: i64 = 999_999;

/// One test point: a pad, a drilled pad or a bare hole.
#[derive(Debug, Clone, PartialEq)]
pub(super) struct Terminal {
    pub net: String,
    pub refdes: String,
    pub pin: String,
    /// Drill diameter in millimetres and whether it is plated.
    pub drill: Option<(f64, bool)>,
    /// `0` for both sides, `1` for top, the layer count for bottom.
    pub access: u8,
    pub at: (f64, f64),
    pub size: (f64, f64),
}

fn microns(mm: f64) -> i64 {
    (mm * 1000.0).round() as i64
}

fn coord(axis: char, mm: f64) -> String {
    let v = microns(mm).clamp(-MAX_COORD, MAX_COORD);
    let sign = if v < 0 { '-' } else { '+' };
    format!("{axis}{sign}{:06}", v.abs())
}

fn record(t: &Terminal, net: &str) -> String {
    let (code, drill) = match t.drill {
        Some((d, plated)) => {
            let kind = if plated { 'P' } else { 'U' };
            let code = if plated { "317" } else { "367" };
            (code, format!("D{:04}{kind}", microns(d).clamp(0, MAX_SIZE)))
        }
        None => ("327", " ".repeat(6)),
    };
    let mask = match (t.drill, t.access) {
        (Some(_), _) => 0,
        (None, 1) => 2,
        (None, _) => 1,
    };
    let size = |mm: f64| microns(mm).clamp(0, MAX_SIZE);
    format!(
        "{code}{net:<14.14}   {:<6.6}-{:<4.4}M{drill}A{:02}{}{}X{:04}Y{:04}R000 S{mask}",
        t.refdes,
        t.pin,
        t.access,
        coord('X', t.at.0),
        coord('Y', t.at.1),
        size(t.size.0),
        size(t.size.1)
    )
}

fn aliases(terminals: &[Terminal]) -> BTreeMap<String, String> {
    let mut long: Vec<&str> = terminals
        .iter()
        .map(|t| t.net.as_str())
        .filter(|n| n.len() > NAME_WIDTH)
        .collect();
    long.sort_unstable();
    long.dedup();
    let named = long.into_iter().enumerate();
    named
        .map(|(i, n)| (n.to_string(), format!("NNAME{}", i + 1)))
        .collect()
}

/// Renders the IPC-D-356A netlist of `circuit` for the job `title`.
pub fn ipc356(circuit: &Circuit, netlist: &Netlist, title: &str) -> String {
    let layers = circuit
        .model()
        .boards
        .first()
        .and_then(|b| b.num_layers)
        .map_or(2, |n| u8::try_from(n).unwrap_or(2));
    let all = terminals::terminals(circuit, netlist, layers);
    let alias = aliases(&all);
    let version = env!("CARGO_PKG_VERSION");
    let mut out = vec![
        format!("C  IPC-D-356A netlist generated by Fusible {version}"),
        format!("P  JOB   {title}"),
        "P  CODE  00".to_string(),
        "P  UNITS CUST 1".to_string(),
        "P  DIM   N".to_string(),
    ];
    out.extend(
        alias
            .iter()
            .map(|(name, short)| format!("P  {short:<8} {name}")),
    );
    out.extend(
        all.iter()
            .map(|t| record(t, alias.get(&t.net).unwrap_or(&t.net))),
    );
    out.push("999".to_string());
    out.join("\n") + "\n"
}
