//! `README.txt` of the fab bundle: which board, which Fusible, when, and
//! what each file inside `gerbers.zip` is.

use crate::config::Date;

/// What a Gerber or drill file name holds, for the layer map.
fn describe(file: &str) -> String {
    let known = match file {
        "Edge_Cuts.gbr" => "board outline",
        "F_Cu.gbr" => "top copper",
        "B_Cu.gbr" => "bottom copper",
        "F_Mask.gbr" => "top solder mask",
        "B_Mask.gbr" => "bottom solder mask",
        "F_Paste.gbr" => "top solder paste",
        "B_Paste.gbr" => "bottom solder paste",
        "F_Silk.gbr" => "top silkscreen",
        "B_Silk.gbr" => "bottom silkscreen",
        "drill_pth.drl" => "plated drills (Excellon)",
        "drill_npth.drl" => "non-plated drills (Excellon)",
        _ => "",
    };
    match (
        known,
        file.strip_prefix("In")
            .and_then(|r| r.strip_suffix("_Cu.gbr")),
    ) {
        ("", Some(n)) => format!("inner copper {n}"),
        ("", None) => "other".to_string(),
        (text, _) => text.to_string(),
    }
}

/// Renders `README.txt` for `board`, listing `files` from `gerbers.zip`.
pub fn readme<'a>(board: &str, date: Date, files: impl Iterator<Item = &'a str>) -> String {
    let mut out = format!(
        "Board: {board}\nGenerated by: Fusible {}\nDate: {date}\nUnits: millimetres\n\n\
         Layer map (gerbers.zip):\n",
        env!("CARGO_PKG_VERSION")
    );
    for file in files {
        out.push_str(&format!("  {file:<16} {}\n", describe(file)));
    }
    out.push_str(
        "\nOther files:\n  \
         circuit.json     tscircuit Circuit JSON the files come from\n  \
         netlist.ipc      IPC-D-356A test netlist (UNITS CUST 1)\n  \
         centroid.csv     pick-and-place, mm, degrees counter-clockwise seen from the top\n  \
         bom.csv          bill of materials\n",
    );
    out
}
